export function t(lang: LangCode, key: keyof TranslationKeys): string {
  return translations[lang]?.[key] ?? translations.en[key] ?? key;
}

export async function saveLanguage(code: LangCode): Promise<void> {
  await AsyncStorage.setItem(LANG_KEY, code);
}

export async function loadLanguage(): Promise<LangCode | null> {
  const val = await AsyncStorage.getItem(LANG_KEY);
  if (val && val in translations) return val as LangCode;
  return null;
}

// --- Context types ---
export type LanguageContextValue = {
  lang: LangCode;
  setLang: (code: LangCode) => void;
  T: (key: keyof TranslationKeys) => string;
};

export const LanguageContext = createContext<LanguageContextValue>({
  lang: 'en',
  setLang: () => {},
  T: (key) => translations.en[key] ?? key,
});

export function useLanguage() {
  return useContext(LanguageContext);
}
