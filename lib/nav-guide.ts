// ---------- Persistence -------------------------------------------------

export async function hasCompletedNavGuide(): Promise<boolean> {
  try {
    const v = await AsyncStorage.getItem(COMPLETED_KEY);
    return v === '1';
  } catch {
    return false;
  }
}

export async function markNavGuideCompleted(): Promise<void> {
  try {
    await AsyncStorage.setItem(COMPLETED_KEY, '1');
  } catch {
    /* ignore */
  }
}

export async function resetNavGuide(): Promise<void> {
  try {
    await AsyncStorage.removeItem(COMPLETED_KEY);
  } catch {
    /* ignore */
  }
}
